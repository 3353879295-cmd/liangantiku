import { readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const functionRoot = join(root, 'cloudfunctions', 'accountSync');
const outputFile = join(functionRoot, 'index.js');
const check = process.argv.slice(2).includes('--check');

if (process.argv.slice(2).some((argument) => argument !== '--check')) {
  throw new Error('Usage: node scripts/build-account-sync-cloud-function.mjs [--check]');
}

const options = {
  entryPoints: [join(functionRoot, 'src', 'index.js')],
  outfile: outputFile,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  external: ['wx-server-sdk'],
  banner: {
    js: '/** @noformat */\n// This file is automatically generated by scripts/build-account-sync-cloud-function.mjs. Do not edit directly.\n',
  },
};

if (!check) {
  await build(options);
  process.stdout.write('Built cloudfunctions/accountSync/index.js\n');
} else {
  const result = await build({ ...options, write: false });
  const bundled = result.outputFiles[0].text;
  const current = await readFile(outputFile, 'utf8');

  if (current !== bundled) {
    throw new Error('accountSync bundle is stale. Run: npm run build:account-sync');
  }

  process.stdout.write('accountSync bundle is current\n');
}
